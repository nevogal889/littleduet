#!/usr/bin/env python3
"""Imports the video teammate's flat song icons (video/ld_icons.py) as vector shapes so the
app draws the same characters with react-native-svg.

    python3 scripts/import-icons.py   ->  src/components/art/iconShapes.ts

Records every drawing primitive on the 100x100 grid instead of rasterising it.
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
VIDEO = os.path.join(os.path.dirname(APP), "video")
sys.path.insert(0, VIDEO)
import ld_icons  # noqa: E402

S = ld_icons.S


def hexc(c):
    if len(c) == 4 and c[3] == 0:
        return None
    return "#%02X%02X%02X" % tuple(c[:3])


class RecDraw:
    """Stands in for ImageDraw for icons that draw on p.d directly (pixel units)."""

    def __init__(self, ops):
        self.ops = ops

    def ellipse(self, box, fill=None):
        x0, y0, x1, y1 = [v / S for v in box]
        self.ops.append({"t": "e", "x0": x0, "y0": y0, "x1": x1, "y1": y1, "c": hexc(fill)})

    def pieslice(self, box, a0, a1, fill=None):
        x0, y0, x1, y1 = [v / S for v in box]
        self.ops.append({"t": "pie", "x0": x0, "y0": y0, "x1": x1, "y1": y1, "a0": a0, "a1": a1, "c": hexc(fill)})


class RecPen(ld_icons.Pen):
    def __init__(self):
        self.ops = []
        self.d = RecDraw(self.ops)

    def E(self, x0, y0, x1, y1, c):
        self.ops.append({"t": "e", "x0": x0, "y0": y0, "x1": x1, "y1": y1, "c": hexc(c)})

    def R(self, x0, y0, x1, y1, c, r=0):
        self.ops.append({"t": "r", "x0": x0, "y0": y0, "x1": x1, "y1": y1, "r": r, "c": hexc(c)})

    def P(self, pts, c):
        self.ops.append({"t": "p", "pts": [[round(x, 2), round(y, 2)] for x, y in pts], "c": hexc(c)})

    def L(self, pts, c, w):
        self.ops.append({"t": "l", "pts": [[round(x, 2), round(y, 2)] for x, y in pts], "w": w, "c": hexc(c)})

    def A(self, x0, y0, x1, y1, a0, a1, c, w):
        self.ops.append({"t": "a", "x0": x0, "y0": y0, "x1": x1, "y1": y1, "a0": a0, "a1": a1, "w": w, "c": hexc(c)})


def rnd(v):
    return round(v, 2) if isinstance(v, float) else v


out = {}
for name, fn in sorted(ld_icons.ICONS.items()):
    p = RecPen()
    fn(p)
    ops = []
    for op in p.ops:
        op = {k: rnd(v) for k, v in op.items()}
        if op.get("c") is None:
            op["t"] = "erase" if op["t"] in ("e", "r", "p") else op["t"]
            op["c"] = "#000000"
        ops.append(op)
    out[name] = ops

dest = os.path.join(APP, "src", "components", "art", "iconShapes.ts")
os.makedirs(os.path.dirname(dest), exist_ok=True)
with open(dest, "w") as f:
    f.write("// GENERATED by scripts/import-icons.py from video/ld_icons.py. Do not edit.\n")
    f.write("export type IconOp = { t: string; c: string; [k: string]: any };\n")
    f.write("export const ICON_SHAPES: Record<string, IconOp[]> = ")
    f.write(json.dumps(out, separators=(",", ":")))
    f.write(";\n")
print("icons:", len(out), "->", os.path.relpath(dest, APP))
