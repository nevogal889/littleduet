import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const ROOT = path.resolve(APP, '..');
export const CONTENT = path.join(ROOT, 'content');
export const VIDEO_OUT = path.join(ROOT, 'video', 'out');
export const VIDEO_SAMPLES = path.join(ROOT, 'video', 'samples');
export const DATA = path.join(APP, 'src', 'data');
export const DATA_LESSONS = path.join(DATA, 'lessons');
export const MEDIA = path.join(APP, 'public', 'media');

export function readJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

/** Real catalog if the content teammate has produced it, else the seed. */
export function sourceSongsPath() {
  const real = path.join(CONTENT, 'songs.json');
  return fs.existsSync(real) ? real : path.join(CONTENT, 'seed-songs.json');
}

/**
 * Regenerates src/data/lessons/summary.json (every class WITHOUT its segments, small and
 * bundled for the catalog) and index.ts (LESSONS = summaries; fullLesson() lazily requires
 * the full file, so the big timelines are only evaluated when a class is opened).
 */
export function writeLessonIndex() {
  const files = fs
    .readdirSync(DATA_LESSONS)
    .filter((f) => f.endsWith('.json') && f !== 'summary.json')
    .sort();
  const summary = {};
  for (const f of files) {
    const l = JSON.parse(fs.readFileSync(path.join(DATA_LESSONS, f), 'utf8'));
    summary[f.replace(/\.json$/, '')] = {
      songId: l.songId,
      ...(l.curriculum ? { curriculum: l.curriculum } : {}),
      ...(l.songSummary ? { songSummary: l.songSummary } : {}),
      ...(l.skillMap ? { skillMap: l.skillMap } : {}),
      classes: l.classes.map(({ segments, ...c }) => ({ ...c, segments: [] })),
    };
  }
  fs.writeFileSync(path.join(DATA_LESSONS, 'summary.json'), JSON.stringify(summary));
  const lines = [
    '// GENERATED by scripts/sync-content.mjs / scripts/make-standins.mjs. Do not edit.',
    "import type { Lesson } from '../../types';",
    "import summary from './summary.json';",
    '',
    '/** Every lesson with class metadata only (segments: []). Small enough to bundle eagerly. */',
    'export const LESSONS: Record<string, Lesson> = summary as unknown as Record<string, Lesson>;',
    '',
    '/* eslint-disable @typescript-eslint/no-require-imports */',
    'const FULL: Record<string, () => Lesson> = {',
    ...files.map((f) => `  ${JSON.stringify(f.replace(/\.json$/, ''))}: () => require('./${f}') as Lesson,`),
    '};',
    '',
    '/** Full lesson (with segment timelines), loaded on first use. */',
    'export function fullLesson(songId: string): Lesson | undefined {',
    '  return FULL[songId]?.();',
    '}',
    '',
  ];
  fs.writeFileSync(path.join(DATA_LESSONS, 'index.ts'), lines.join('\n'));
  return files.length;
}
