#!/usr/bin/env node
// Copies the teammates' content into the app. Safe to re-run any time.
//
//   content/songs.json (or seed-songs.json) -> src/data/songs.json
//   copy/strings.en.json                    -> src/data/strings.en.json
//   content/lessons/<songId>.json           -> src/data/lessons/<songId>.json (+ index.ts)
//   video/samples/<Note>.mp3                -> assets/samples/<Note>.mp3 (bundled, '#' -> 's') + src/data/samples.ts
//   video/out/<songId>/<classId>.mp4/.jpg   -> public/media/<songId>/  (web dev only)
//   content/covers/<songId>.jpg             -> public/media/<songId>/photo.jpg + src/data/media.json
//
// Real builds stream videos/thumbs from EXPO_PUBLIC_VIDEO_BASE_URL instead of public/media.
// Flags: --no-media (skip videos), --webm (also transcode VP8 copies for web dev),
//        --prune (delete lessons for songs no longer in the catalog)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { APP, ROOT, CONTENT, DATA, DATA_LESSONS, MEDIA, VIDEO_OUT, VIDEO_SAMPLES, readJson, sourceSongsPath, writeLessonIndex } from './lib/paths.mjs';

const args = new Set(process.argv.slice(2));
// --webm (all songs) or --webm=songA,songB (only those): VP8 copies for browsers without H.264.
const webmArg = process.argv.find((a) => a.startsWith('--webm'));
const webmOnly = webmArg?.includes('=') ? new Set(webmArg.split('=')[1].split(',')) : null;
const wantWebm = (songId) => !!webmArg && (!webmOnly || webmOnly.has(songId));
const report = [];

// 1. songs
const songsPath = sourceSongsPath();
const songs = readJson(songsPath);
fs.mkdirSync(DATA_LESSONS, { recursive: true });
fs.writeFileSync(path.join(DATA, 'songs.json'), JSON.stringify(songs, null, 2));
report.push(`songs: ${songs.length} from ${path.relative(APP, songsPath)}`);

// 1b. user-facing copy (copy teammate) -> src/data/strings.en.json
const COPY = path.join(ROOT, 'copy', 'strings.en.json');
if (fs.existsSync(COPY)) {
  fs.copyFileSync(COPY, path.join(DATA, 'strings.en.json'));
  report.push('copy: strings.en.json copied');
} else if (!fs.existsSync(path.join(DATA, 'strings.en.json'))) {
  fs.writeFileSync(path.join(DATA, 'strings.en.json'), '{}\n');
  report.push('copy: copy/strings.en.json not found, app overlay strings only');
}

// 2. lessons
const lessonSrc = path.join(CONTENT, 'lessons');
let copied = 0;
const missing = [];
for (const s of songs) {
  const src = path.join(lessonSrc, `${s.id}.json`);
  if (fs.existsSync(src)) {
    fs.copyFileSync(src, path.join(DATA_LESSONS, `${s.id}.json`));
    copied++;
  } else if (!fs.existsSync(path.join(DATA_LESSONS, `${s.id}.json`))) {
    missing.push(s.id);
  }
}
if (args.has('--prune')) {
  const ids = new Set(songs.map((s) => `${s.id}.json`));
  for (const f of fs.readdirSync(DATA_LESSONS)) if (f.endsWith('.json') && !ids.has(f)) fs.rmSync(path.join(DATA_LESSONS, f));
}
const indexed = writeLessonIndex();
report.push(`lessons: ${copied} copied from content/lessons, ${indexed} indexed`);
if (missing.length) report.push(`  no lesson yet for: ${missing.join(', ')} (run scripts/make-standins.mjs)`);

// 3. piano samples (bundled so taps are instant and offline)
const SAMPLES = path.join(APP, 'assets', 'samples');
fs.mkdirSync(SAMPLES, { recursive: true });
const safe = (note) => note.replace('#', 's');
let sampleNotes = [];
if (fs.existsSync(VIDEO_SAMPLES)) {
  for (const f of fs.readdirSync(VIDEO_SAMPLES)) {
    const m = /^([A-G]#?\d)\.mp3$/.exec(f);
    if (!m) continue;
    fs.copyFileSync(path.join(VIDEO_SAMPLES, f), path.join(SAMPLES, `${safe(m[1])}.mp3`));
    sampleNotes.push({ note: m[1], file: `${safe(m[1])}.mp3` });
  }
}
if (!sampleNotes.length) {
  sampleNotes = synthesizeSamples(SAMPLES);
  report.push(`samples: none in video/samples, synthesized ${sampleNotes.length} WAV fallbacks`);
} else {
  report.push(`samples: ${sampleNotes.length} copied from video/samples`);
}
sampleNotes.sort((a, b) => a.note.localeCompare(b.note));
fs.writeFileSync(
  path.join(DATA, 'samples.ts'),
  [
    '// GENERATED by scripts/sync-content.mjs. Do not edit.',
    '// Bundled piano samples keyed by scientific pitch (sharps).',
    'export const SAMPLE_ASSETS: Record<string, number> = {',
    ...sampleNotes.map((s) => `  ${JSON.stringify(s.note)}: require('../../assets/samples/${s.file}'),`),
    '};',
    '',
  ].join('\n'),
);

// 4. videos + thumbnails for web dev
if (!args.has('--no-media')) {
  let vids = 0;
  let thumbs = 0;
  if (fs.existsSync(VIDEO_OUT)) {
    for (const songId of fs.readdirSync(VIDEO_OUT)) {
      const dir = path.join(VIDEO_OUT, songId);
      if (songId.startsWith('_') || !fs.statSync(dir).isDirectory()) continue;
      fs.mkdirSync(path.join(MEDIA, songId), { recursive: true });
      for (const f of fs.readdirSync(dir)) {
        if (!/\.(mp4|webm|jpg)$/.test(f)) continue;
        const dest = path.join(MEDIA, songId, f);
        fs.copyFileSync(path.join(dir, f), dest);
        if (f.endsWith('.jpg')) thumbs++;
        else vids++;
        // Browsers without H.264 (e.g. Playwright Chromium) get a VP8 copy; the web player picks it.
        const webm = dest.replace(/\.mp4$/, '.webm');
        if (wantWebm(songId) && f.endsWith('.mp4') && (!fs.existsSync(webm) || fs.statSync(webm).mtimeMs < fs.statSync(path.join(dir, f)).mtimeMs)) {
          execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', dest, '-vf', 'scale=640:-2', '-c:v', 'libvpx', '-b:v', '600k', '-deadline', 'realtime', '-cpu-used', '8', '-c:a', 'libopus', '-b:a', '64k', webm]);
        }
      }
    }
    report.push(`media: ${vids} videos, ${thumbs} thumbnails -> public/media`);
  } else {
    report.push('media: video/out not found yet (stand-ins: node scripts/make-standins.mjs --videos)');
  }
}

// 5. song covers: founder's real photos win over the lesson-style covers.
//    content/covers/<songId>.jpg -> public/media/<songId>/photo.jpg (native: <VIDEO_BASE_URL>/<songId>/photo.jpg)
//    src/data/media.json tells the app which images exist so it never requests missing ones.
const PHOTOS = path.join(CONTENT, 'covers');
const manifest = {};
let photos = 0;
for (const s of songs) {
  const photo = path.join(PHOTOS, `${s.id}.jpg`);
  const hasPhoto = fs.existsSync(photo);
  if (hasPhoto) {
    photos++;
    if (!args.has('--no-media')) {
      fs.mkdirSync(path.join(MEDIA, s.id), { recursive: true });
      fs.copyFileSync(photo, path.join(MEDIA, s.id, 'photo.jpg'));
    }
  }
  const hasCover = fs.existsSync(path.join(VIDEO_OUT, s.id, 'cover.jpg'));
  manifest[s.id] = { photo: hasPhoto, cover: hasCover };
}
fs.writeFileSync(path.join(DATA, 'media.json'), JSON.stringify(manifest));
report.push(`covers: ${photos} real photos, ${Object.values(manifest).filter((m) => m.cover).length} lesson-style covers (manifest src/data/media.json)`);

console.log(report.join('\n'));

// Simple decaying-harmonic tones so the app never ships without sound.
function synthesizeSamples(dir) {
  const NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
  const out = [];
  const rate = 22050;
  for (let midi = 48; midi <= 84; midi++) {
    const note = `${NAMES[midi % 12]}${Math.floor(midi / 12) - 1}`;
    const f0 = 440 * Math.pow(2, (midi - 69) / 12);
    const n = Math.floor(rate * 1.2);
    const buf = Buffer.alloc(44 + n * 2);
    buf.write('RIFF', 0); buf.writeUInt32LE(36 + n * 2, 4); buf.write('WAVE', 8); buf.write('fmt ', 12);
    buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22); buf.writeUInt32LE(rate, 24);
    buf.writeUInt32LE(rate * 2, 28); buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34); buf.write('data', 36); buf.writeUInt32LE(n * 2, 40);
    for (let i = 0; i < n; i++) {
      const t = i / rate;
      const env = Math.min(1, t / 0.005) * Math.exp(-3.2 * t);
      const v = (Math.sin(2 * Math.PI * f0 * t) + 0.4 * Math.sin(4 * Math.PI * f0 * t) + 0.15 * Math.sin(6 * Math.PI * f0 * t)) * env * 0.45;
      buf.writeInt16LE(Math.max(-32767, Math.min(32767, Math.round(v * 32767))), 44 + i * 2);
    }
    const file = `${note.replace('#', 's')}.wav`;
    fs.writeFileSync(path.join(dir, file), buf);
    out.push({ note, file });
  }
  return out;
}
